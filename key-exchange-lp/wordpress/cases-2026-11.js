async function kmPostCases() {
  const B = (name, attrs = {}, inner = []) => wp.blocks.createBlock(name, attrs, inner);
  const P = (content) => B("core/paragraph", { content });
  const media = {};
  for (const c of KM_CASES) for (const [id] of c.photos) media[id] = (await wp.apiFetch({ path: `/wp/v2/media/${id}?_fields=id,source_url` })).source_url;
  const out = [];
  for (const c of KM_CASES) {
    const blocks = [
      P(`依頼現場：${c.place}`),
      P(`依頼内容：${c.ask}`),
      P(`対応内容：${c.work}`),
      ...c.photos.map(([id, alt]) => B("core/image", { id, url: media[id], alt: `${c.short}での${alt}`, sizeSlug: "large", linkDestination: "none" })),
      P(`鍵マッハ24は、東京都内と埼玉県南部に24時間出張しています。家の鍵をなくした・家に入れないときは<a href="https://h-gate.jp/kagi-funshitsu/">鍵開けのページ</a>、料金は<a href="https://h-gate.jp/price/">料金表</a>をご覧ください。`),
    ];
    const data = {
      title: c.title, slug: c.slug, date: c.date, status: "publish", categories: [1], featured_media: c.photos[c.photos.length - 1][0],
      content: wp.blocks.serialize(blocks),
      excerpt: `${c.place}で、${c.title.replace(c.short + "で", "")}をしました。${c.ask}というご依頼に、ご本人確認のうえ対応した鍵マッハ24の作業事例です。`,
      veu_head_title_object: { title: `${c.title}｜作業事例 鍵マッハ24`, add_site_title: "" },
    };
    const ex = (await wp.apiFetch({ path: `/wp/v2/posts?slug=${c.slug}&status=publish,draft,future&context=edit&_fields=id` }))[0];
    let id = ex?.id;
    // WAFは「長い本文つきの新規作成」を止めるので、先に空の下書きを作ってから中身を入れる
    if (!id) id = (await wp.apiFetch({ path: "/wp/v2/posts", method: "POST", data: { title: c.slug, slug: c.slug, status: "draft" } })).id;
    const r = await wp.apiFetch({ path: `/wp/v2/posts/${id}`, method: "POST", data });
    out.push(`${r.id} ${r.status} ${r.link}`);
  }
  return out;
}
